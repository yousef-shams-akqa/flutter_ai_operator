import 'package:go_router/go_router.dart';

/// Navigation context for the AI layer, derived from [GoRouter].
///
/// The result of [getRouterContext] is read by [GoRouterContextSource] and
/// appended to the user's request, so the model can pick correct navigation
/// targets.
extension GoRouterStateContext on GoRouter {
  /// Current active navigation stack.
  /// Example: '/home → /home/settings → /home/settings/profile'
  String currentStack() {
    return routerDelegate.currentConfiguration.matches
        .map((m) => m.matchedLocation)
        .join(' → ');
  }

  /// Complete configured route tree.
  /// Example: '/home { /home/settings { /home/settings/profile } }'
  String routeTree() {
    String build(List<RouteBase> routes) {
      return routes
          .map((route) {
            final path = route is GoRoute
                ? route.path
                : route.runtimeType.toString();

            final children = route is StatefulShellRoute
                ? route.branches.expand((b) => b.routes).toList()
                : route.routes;

            return children.isEmpty ? path : '$path { ${build(children)} }';
          })
          .join(', ');
    }

    return build(configuration.routes);
  }

  /// Full path of every [GoRoute], parents before their children.
  /// Example: ['/home', '/home/settings', '/products/:productId']
  List<String> routePaths() {
    final paths = <String>[];

    void collect(List<RouteBase> routes, {String parentPath = ''}) {
      for (final route in routes) {
        if (route is GoRoute) {
          final path = _joinPath(parentPath, route.path);
          paths.add(path);
          collect(route.routes, parentPath: path);
        } else if (route is StatefulShellRoute) {
          for (final branch in route.branches) {
            collect(branch.routes, parentPath: parentPath);
          }
        } else {
          collect(route.routes, parentPath: parentPath);
        }
      }
    }

    collect(configuration.routes);
    return paths.toSet().toList();
  }

  /// Dynamic route paths and the string-map shape used to fill their parameters.
  /// Example: `/products/:productId => {"productId": "<string>"}, /products/:productId/reviews/:reviewId => {"productId": "<string>", "reviewId": "<string>"}`
  String routeParameterShapes() {
    final shapes = <String>[];
    for (final path in routePaths()) {
      final placeholders = RegExp(r':([A-Za-z0-9_]+)(\?)?')
          .allMatches(path)
          .toList(growable: false);
      if (placeholders.isEmpty) continue;

      final values = placeholders
          .map((match) {
            final suffix = match.group(2) == null ? '' : ' (optional)';
            return '"${match.group(1)}": "<string>$suffix"';
          })
          .join(', ');
      shapes.add('$path => {$values}');
    }
    return shapes.join(', ');
  }

  String _joinPath(String parentPath, String path) {
    if (path.startsWith('/')) return path;
    if (parentPath.isEmpty) return path;
    return parentPath.endsWith('/') ? '$parentPath$path' : '$parentPath/$path';
  }

  /// Returns the app navigation context as labeled text lines: the current
  /// stack, the route tree, and (only when present) dynamic route parameters.
  ///
  /// The text starts with a blank line because it is appended directly to the
  /// final user message.
  String getRouterContext() {
    final parameterShapes = routeParameterShapes();
    final lines = [
      'App navigation context (generated by the app):',
      'Current stack: ${currentStack()}',
      'Route tree: ${routeTree()}',
      if (parameterShapes.isNotEmpty)
        'Dynamic route parameters: $parameterShapes',
    ];
    return '\n\n${lines.join('\n')}\n';
  }
}
