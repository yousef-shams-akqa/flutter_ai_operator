import 'package:flutter_app_copilot/flutter_app_copilot.dart';
import 'package:flutter/widgets.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:go_router/go_router.dart';

void main() {
  testWidgets('context contains evaluated paths and updates after navigation', (
    tester,
  ) async {
    final router = GoRouter(
      initialLocation: '/home/settings/profile',
      overridePlatformDefaultLocation: true,
      routes: [
        GoRoute(
          path: '/home',
          builder: (_, _) => const SizedBox(),
          routes: [
            GoRoute(
              path: 'settings',
              builder: (_, _) => const SizedBox(),
              routes: [
                GoRoute(path: 'profile', builder: (_, _) => const SizedBox()),
              ],
            ),
          ],
        ),
      ],
    );
    addTearDown(router.dispose);
    await tester.pumpWidget(
      WidgetsApp.router(routerConfig: router, color: const Color(0xFFFFFFFF)),
    );
    await tester.pumpAndSettle();
    expect(
      router.getRouterContext(),
      '\n\nApp navigation context (generated by the app):\n'
      'Current stack: /home → /home/settings → /home/settings/profile\n'
      'Route tree: /home { settings { profile } }\n',
    );

    router.go('/home');
    await tester.pumpAndSettle();
    expect(router.currentStack(), '/home');
    expect(
      router.getRouterContext(),
      '\n\nApp navigation context (generated by the app):\n'
      'Current stack: /home\n'
      'Route tree: /home { settings { profile } }\n',
    );
    await tester.pumpWidget(const SizedBox());
  });

  testWidgets('route tree includes siblings and shell children', (_) async {
    final router = GoRouter(
      initialLocation: '/home',
      routes: [
        ShellRoute(
          builder: (_, _, child) => child,
          routes: [
            GoRoute(path: '/home', builder: (_, _) => const SizedBox()),
            GoRoute(path: '/settings', builder: (_, _) => const SizedBox()),
          ],
        ),
        GoRoute(path: '/about', builder: (_, _) => const SizedBox()),
      ],
    );
    addTearDown(router.dispose);

    expect(router.routeTree(), 'ShellRoute { /home, /settings }, /about');
  });

  testWidgets('route parameter shapes cover nested, shell and optional paths', (
    _,
  ) async {
    final router = GoRouter(
      initialLocation: '/products/1',
      routes: [
        ShellRoute(
          builder: (_, _, child) => child,
          routes: [
            GoRoute(
              path: '/products/:productId',
              builder: (_, _) => const SizedBox(),
              routes: [
                GoRoute(
                  path: 'reviews/:reviewId',
                  builder: (_, _) => const SizedBox(),
                ),
              ],
            ),
          ],
        ),
        GoRoute(path: '/users/:userId?', builder: (_, _) => const SizedBox()),
        GoRoute(path: '/about', builder: (_, _) => const SizedBox()),
      ],
    );
    addTearDown(router.dispose);

    expect(
      router.routeParameterShapes(),
      '/products/:productId => {"productId": "<string>"}, '
      '/products/:productId/reviews/:reviewId => '
      '{"productId": "<string>", "reviewId": "<string>"}, '
      '/users/:userId? => {"userId": "<string> (optional)"}',
    );
    expect(
      router.getRouterContext(),
      contains(
        '\nDynamic route parameters: ${router.routeParameterShapes()}\n',
      ),
    );
  });

  testWidgets('route parameter shapes are empty without dynamic routes', (
    _,
  ) async {
    final router = GoRouter(
      initialLocation: '/about',
      routes: [GoRoute(path: '/about', builder: (_, _) => const SizedBox())],
    );
    addTearDown(router.dispose);

    expect(router.routeParameterShapes(), isEmpty);
    expect(router.getRouterContext(), isNot(contains('Dynamic route')));
  });

  testWidgets('route tree includes every stateful shell branch', (_) async {
    final router = GoRouter(
      initialLocation: '/feed',
      routes: [
        StatefulShellRoute.indexedStack(
          builder: (_, _, shell) => shell,
          branches: [
            StatefulShellBranch(
              routes: [
                GoRoute(path: '/feed', builder: (_, _) => const SizedBox()),
              ],
            ),
            StatefulShellBranch(
              routes: [
                GoRoute(
                  path: '/settings',
                  builder: (_, _) => const SizedBox(),
                  routes: [
                    GoRoute(
                      path: 'profile',
                      builder: (_, _) => const SizedBox(),
                    ),
                  ],
                ),
              ],
            ),
          ],
        ),
      ],
    );
    addTearDown(router.dispose);

    expect(
      router.routeTree(),
      'StatefulShellRoute { /feed, /settings { profile } }',
    );
  });
}
